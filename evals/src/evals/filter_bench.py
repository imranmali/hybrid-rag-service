"""Pre- vs post-filter pushdown benchmark (ADR 0006): `results_filter_pushdown.md`."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from evals.runner import RunContext, RunOptions, RunOutcome, make_run_id, run_config

STRATEGIES = ("pre", "post", "auto")
HEADER = """# Filter pushdown benchmark

> Generated by `uv run evals filter-bench` from the run files linked below. **Do not edit by hand.**

Filter questions only, retrieval only (generation, rerank and routing off). `pre` = exact distance
sort over the filtered chunk set, `post` = HNSW over-fetch then filter, `auto` = the service picks
by estimated selectivity.
"""


def _f(v: float | None, digits: int = 3) -> str:
    return "-" if v is None else f"{v:.{digits}f}"


def render(outcomes: dict[str, RunOutcome], evals_dir: Path) -> str:
    rows = []
    for strategy in STRATEGIES:
        o = outcomes[strategy]
        rec = o.record
        m = rec["metrics"]
        vec = m["latency"]["stages"].get("retrieve.vector", {})
        under = m["filters"]["underfilled_rate"]
        chosen = (
            ", ".join(f"{k}: {v}" for k, v in sorted(m["filters"]["strategies"].items())) or "-"
        )
        link = o.path.relative_to(evals_dir).as_posix()
        rows.append(
            "| "
            + " | ".join(
                [
                    f"`{strategy}` ([run]({link}))",
                    str(m["retrieval"]["recall_at_20"]["n"]),
                    _f(m["retrieval"]["recall_at_20"]["mean"]),
                    _f(m["retrieval"]["ndcg_at_10"]["mean"]),
                    _f(vec.get("p50"), 1),
                    _f(vec.get("p95"), 1),
                    "-" if under is None else f"{under * 100:.1f}%",
                    chosen,
                ]
            )
            + " |"
        )
    head = (
        "| Strategy | n | R@20 | nDCG@10 | retrieve.vector p50 ms | p95 ms "
        "| underfilled % | strategies chosen |"
    )
    sep = "|---|---|---|---|---|---|---|---|"
    any_rec: dict[str, Any] = next(iter(outcomes.values())).record
    prov = (
        f"\nRun `{any_rec['run_id']}`, git `{any_rec['git']['sha']}`, seed {any_rec['seed']}, "
        f"dataset sha256 `{any_rec['dataset']['sha256']}`.\n"
    )
    return HEADER + "\n" + "\n".join([head, sep, *rows]) + "\n" + prov


def run_filter_bench(
    configs_dir: Path, opts: RunOptions, ctx: RunContext
) -> tuple[Path, dict[str, RunOutcome]]:
    run_id = make_run_id(ctx)
    outcomes = {
        s: run_config(configs_dir / f"filter-{s}.yaml", opts, ctx, run_id=run_id)
        for s in STRATEGIES
    }
    path = ctx.evals_dir / "results_filter_pushdown.md"
    path.write_text(render(outcomes, ctx.evals_dir), encoding="utf-8")
    return path, outcomes
