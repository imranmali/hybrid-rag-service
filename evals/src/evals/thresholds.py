"""CI regression thresholds (design D9): baseline minus tolerance, floored at 0."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

TOLERANCE = {
    "ndcg_at_10": 0.03,
    "recall_at_20": 0.03,
    "route_accuracy": 0.05,
    "sql_accuracy": 0.10,
}
GRID_CONFIGS = ("01-vector", "02-hybrid", "03-filters", "04-contextual", "05-rerank", "06-routing")
ROUTING_CONFIG = "06-routing"
METRICS_FOR = {c: ("ndcg_at_10", "recall_at_20") for c in GRID_CONFIGS}
METRICS_FOR[ROUTING_CONFIG] = ("ndcg_at_10", "recall_at_20", "route_accuracy", "sql_accuracy")


class ThresholdError(Exception):
    """Missing or unusable baseline / threshold input (CLI exit code 3)."""


def metric_value(record: dict[str, Any], metric: str) -> float | None:
    m = record["metrics"]
    if metric in ("ndcg_at_10", "recall_at_20"):
        return m["retrieval"][metric]["mean"]
    if metric == "route_accuracy":
        return m["routing"]["route_accuracy"]["value"]
    if metric == "sql_accuracy":
        return m["routing"]["sql_accuracy"]["value"]
    raise KeyError(metric)


def load_run_dir(run_dir: Path) -> dict[str, dict[str, Any]]:
    """All config run files in a run directory, keyed by config name."""
    if not run_dir.is_dir():
        raise ThresholdError(f"run directory not found: {run_dir}")
    records: dict[str, dict[str, Any]] = {}
    for path in sorted(run_dir.glob("*.json")):
        rec = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(rec, dict) and "config" in rec and "metrics" in rec:
            records[rec["config"]["name"]] = rec
    return records


def build_thresholds(records: dict[str, dict[str, Any]]) -> dict[str, Any]:
    missing = [c for c in GRID_CONFIGS if c not in records]
    if missing:
        raise ThresholdError(f"baseline run is missing configs: {', '.join(missing)}")
    run_ids = {r["run_id"] for r in records.values()}
    if len(run_ids) != 1:
        raise ThresholdError(f"baseline mixes several runs: {sorted(run_ids)}")
    configs: dict[str, dict[str, float]] = {}
    for name in GRID_CONFIGS:
        entry = {}
        for metric in METRICS_FOR[name]:
            value = metric_value(records[name], metric)
            if value is None:
                raise ThresholdError(f"{name}: baseline has no value for {metric}")
            entry[metric] = max(0.0, round(value - TOLERANCE[metric], 3))
        configs[name] = entry
    return {
        "baseline_run": run_ids.pop(),
        "tolerance": dict(TOLERANCE),
        "max_degraded": 0,
        "configs": configs,
    }


def write_thresholds(run_dir: Path, out_path: Path) -> dict[str, Any]:
    data = build_thresholds(load_run_dir(run_dir))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Generated by `uv run evals thresholds --from runs/ci/<run_id>`; do not edit by hand.\n"
        "# Each minimum = baseline metric - tolerance, floored at 0.\n"
    )
    out_path.write_text(header + yaml.safe_dump(data, sort_keys=False), encoding="utf-8")
    return data


def load_thresholds(path: Path) -> dict[str, Any]:
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        raise ThresholdError(f"cannot read thresholds {path}: {exc}") from exc
    if not isinstance(data, dict) or "configs" not in data:
        raise ThresholdError(f"{path} is not a thresholds file (no `configs`)")
    return data
