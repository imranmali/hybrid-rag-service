"""Generate `evals/results.md` from run files only (design D8): every number is traceable to a
file under `evals/runs/`. Nothing here is ever edited by hand.

Runs feed the table by role (see `runner.results_role`):

- `full`: full dataset, generation and judge on; fills every column.
- `retrieval`: full dataset, generation off; fills retrieval, routing and latency columns.
- `gen_subset`: CI subset with generation and judge on; fills the generation/judge columns.

A cell with no measurement behind it shows "—"."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

HEADER = """# Eval results

> Generated by `uv run evals report` from the run files in `evals/runs/`. **Do not edit by hand.**
"""

DASH = "—"
COLUMNS = [
    "#", "Config", "nDCG@10", "R@5", "R@20", "R@50", "MRR", "Route acc.", "SQL acc.",
    "p50 e2e ms", "p95 e2e ms", "p95 rerank ms", "Faithfulness", "Answer rel.", "Abstain acc.",
    "Cost/query (est.)", "Tokens/query", "Degraded", "Mode", "Run", "Gen/judge run",
]  # fmt: skip

LIMITATIONS = """## Limitations

- Small n per question type (e.g. 8 unanswerable); n is shown per metric and no claim of
  statistical significance is made.
- The dataset was LLM-generated and agent-verified against the source chunks; human review is
  pending.
- The judge is the same model family as the generator (self-preference bias is possible).
- Cost/query is an estimate from token counts x `pricing.yaml`; the default prices are 0.
"""

FULL_ROLES = ("full", "retrieval")
GEN_ROLES = ("full", "gen_subset")


def _f(value: float | None, digits: int = 3) -> str:
    return DASH if value is None else f"{value:.{digits}f}"


def _ms(value: float | None) -> str:
    return DASH if value is None else f"{value:,.0f}"


def _mean(d: dict[str, Any] | None) -> float | None:
    return None if not d else d.get("mean")


def _val(d: dict[str, Any] | None) -> float | None:
    return None if not d else d.get("value")


Run = tuple[Path, dict[str, Any]]


def _scan(evals_dir: Path) -> list[Run]:
    found: list[Run] = []
    for path in sorted((evals_dir / "runs").glob("*/*.json")):
        try:
            rec = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if isinstance(rec, dict) and rec.get("results_role"):
            found.append((path, rec))
    return found


def _latest(runs: list[Run], roles: tuple[str, ...]) -> dict[str, Run]:
    best: dict[str, Run] = {}
    for path, rec in runs:
        if rec["results_role"] not in roles:
            continue
        name = rec["config"]["name"]
        if name not in best or rec["finished_at"] > best[name][1]["finished_at"]:
            best[name] = (path, rec)
    return best


def load_rows(evals_dir: Path) -> list[tuple[Run | None, Run | None]]:
    """(main run, gen/judge run) per config, ordered by grid row. The main run supplies the
    retrieval/routing/latency columns; the gen run the generation/judge columns."""
    runs = _scan(evals_dir)
    main, gen = _latest(runs, FULL_ROLES), _latest(runs, GEN_ROLES)
    names = set(main) | set(gen)

    def key(name: str) -> tuple[int, str]:
        rec = (main.get(name) or gen[name])[1]
        return (rec["config"].get("grid_row") or 99, name)

    return [(main.get(n), gen.get(n)) for n in sorted(names, key=key)]


def load_eligible_runs(evals_dir: Path) -> list[Run]:
    """Every run file the table is built from (main runs first, then distinct gen runs)."""
    out: list[Run] = []
    seen: set[Path] = set()
    for main, gen in load_rows(evals_dir):
        for run in (main, gen):
            if run is not None and run[0] not in seen:
                seen.add(run[0])
                out.append(run)
    return out


def _link(evals_dir: Path, path: Path, rec: dict[str, Any]) -> str:
    return f"[{rec['run_id']}]({path.relative_to(evals_dir).as_posix()})"


def _mode(rec: dict[str, Any]) -> str:
    return "full" if rec["results_role"] == "full" else "retrieval-only"


def _row(evals_dir: Path, main: Run | None, gen: Run | None) -> list[str]:
    ref = (main or gen)[1]  # type: ignore[index]
    m = main[1]["metrics"] if main else None
    g = gen[1]["metrics"] if gen else None
    answers = (g or {}).get("answers", {})
    gen_tag = " (ci50)" if gen and gen[1]["results_role"] == "gen_subset" else ""
    deg = DASH
    if main:
        d = main[1]["degraded"]
        deg = f"{d['rate'] * 100:.1f}%" + (" ⚠" if d["count"] else "")
        if main[1]["errors"]["count"]:
            deg += f" ({main[1]['errors']['count']} errors ⚠)"
    cost = (g or {}).get("cost")
    return [
        str(ref["config"].get("grid_row") or DASH),
        f"`{ref['config']['name']}`",
        *(
            [
                _f(_mean(m["retrieval"]["ndcg_at_10"])),
                _f(_mean(m["retrieval"]["recall_at_5"])),
                _f(_mean(m["retrieval"]["recall_at_20"])),
                _f(_mean(m["retrieval"]["recall_at_50"])),
                _f(_mean(m["retrieval"]["mrr"])),
                _f(_val(m["routing"]["route_accuracy"])),
                _f(_val(m["routing"]["sql_accuracy"])),
                _ms(m["latency"]["e2e"]["p50"]),
                _ms(m["latency"]["e2e"]["p95"]),
                _ms(m["latency"]["stages"].get("rerank", {}).get("p95")),
            ]
            if m
            else [DASH] * 10
        ),
        (_f(_mean(answers.get("faithfulness"))) + gen_tag) if "faithfulness" in answers else DASH,
        (_f(_mean(answers.get("answer_relevance"))) + gen_tag)
        if "answer_relevance" in answers
        else DASH,
        (_f(_val(answers.get("abstention_accuracy"))) + gen_tag)
        if "abstention_accuracy" in answers
        else DASH,
        f"{cost['cost_per_query']:.4f} (est.){gen_tag}" if cost else DASH,
        f"{cost['tokens_per_query']:,.0f}{gen_tag}" if cost else DASH,
        deg,
        _mode(main[1]) if main else DASH,
        _link(evals_dir, *main) if main else DASH,
        _link(evals_dir, *gen) if gen else DASH,
    ]


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def render_results(evals_dir: Path, rows: list[tuple[Run | None, Run | None]]) -> str:
    out = [HEADER]
    if not rows:
        out.append("No results runs yet. Run `make eval` to produce them.\n")
        return "\n".join(out)

    mains = [m for m, _ in rows if m]
    gens = [g for _, g in rows if g]
    ds = (mains or gens)[0][1]["dataset"]
    out.append(
        f"Dataset: `{ds['path']}` ({ds['total_records']} questions, sha256 `{ds['sha256']}`). "
        "Questions were LLM-generated and agent-verified; **human review is pending**.\n"
    )
    out.append(
        "How to read the table: **Mode `full`** rows ran the whole dataset with generation and "
        "the judge on. **Mode `retrieval-only`** rows ran the whole dataset with generation "
        "disabled (`--no-generation`), so latency excludes generation and token/cost cells are "
        f"not reported. Generation/judge columns marked `(ci50)` come from the separate "
        f"`Gen/judge run`, which used only the 50-question CI subset. `{DASH}` = not measured. "
        "Route and SQL accuracy of rows with routing disabled are mechanical (every question "
        "goes to the vector route, so SQL accuracy is 0 and route accuracy is the vector share "
        "of the dataset); they only measure the router in the rows where it is enabled.\n"
    )
    out.append("## Ablation grid\n")
    out.append(_table(COLUMNS, [_row(evals_dir, m, g) for m, g in rows]))
    out.append("")

    cov_rows = []
    for m, g in rows:
        ref = (m or g)[1]  # type: ignore[index]
        mm = m[1]["metrics"] if m else None
        gm = (g[1]["metrics"] if g else {}).get("answers", {})
        cov_rows.append(
            [
                f"`{ref['config']['name']}`",
                str(mm["retrieval"]["ndcg_at_10"]["n"]) if mm else DASH,
                str(mm["routing"]["route_accuracy"]["n"]) if mm else DASH,
                str(mm["routing"]["sql_accuracy"]["n"]) if mm else DASH,
                str(gm.get("faithfulness", {}).get("n", DASH)),
                str(gm.get("answer_relevance", {}).get("n", DASH)),
                str(gm.get("faithfulness", {}).get("judge_errors", DASH)),
                str(gm.get("abstention_accuracy", {}).get("n", DASH)),
            ]
        )
    out.append("### Questions covered per metric\n")
    out.append(
        _table(
            ["Config", "Retrieval (n)", "Route (n)", "SQL (n)", "Faithfulness (n)",
             "Answer rel. (n)", "Judge errors", "Abstention (n)"],
            cov_rows,
        )
    )  # fmt: skip
    out.append("")

    if mains:
        stages = sorted({s for _, r in mains for s in r["metrics"]["latency"]["stages"]})
        out.append("## Per-stage latency (ms, p50 / p95)\n")
        header = ["Stage", *[f"`{r['config']['name']}`" for _, r in mains]]
        lat_rows = [
            [
                s,
                *[
                    (
                        f"{_ms(st['p50'])} / {_ms(st['p95'])}"
                        if (st := r["metrics"]["latency"]["stages"].get(s))
                        else DASH
                    )
                    for _, r in mains
                ],
            ]
            for s in stages
        ]
        lat_rows.insert(
            0,
            [
                "server total",
                *[
                    f"{_ms(r['metrics']['latency']['server_total']['p50'])} / "
                    f"{_ms(r['metrics']['latency']['server_total']['p95'])}"
                    for _, r in mains
                ],
            ],
        )
        out.append(_table(header, lat_rows))
        out.append("")

        for _, r in mains:
            if r["config"]["content"]["pipeline"]["routing"]["enabled"]:
                cm = r["metrics"]["routing"]["confusion"]
                out.append(f"## Routing confusion matrix: `{r['config']['name']}`\n")
                out.append(
                    _table(
                        ["expected \\ actual", "sql", "vector"],
                        [
                            [f"**{e}**", str(cm[e]["sql"]), str(cm[e]["vector"])]
                            for e in ("sql", "vector")
                        ],
                    )
                )
                out.append("")

    prov = []
    for _, r in [*mains, *[g for g in gens if g not in mains]]:
        d = r["model_digests"]["digests"]
        prov.append(
            [
                f"`{r['config']['name']}`",
                r["results_role"],
                f"`{r['run_id']}`",
                str(r["seed"]),
                *[f"`{(v or 'unknown')[:12]}`" for v in d.values()],
                f"`{r['git']['sha']}`" + (" (dirty)" if r["git"]["dirty"] else ""),
                "yes" if r["model_digests"]["matches_lock"] else "NO (drift allowed)",
            ]
        )
    ref_run = (mains or gens)[0][1]
    digest_names = list(ref_run["model_digests"]["digests"])
    out.append("## Provenance\n")
    out.append(
        _table(
            ["Config", "Role", "Run id", "Seed", *[f"{n} digest" for n in digest_names],
             "Git sha", "Digests match lock"],
            prov,
        )
    )  # fmt: skip
    out.append("")
    out.append(LIMITATIONS)
    return "\n".join(out)


def write_results(evals_dir: Path) -> Path:
    path = evals_dir / "results.md"
    path.write_text(render_results(evals_dir, load_rows(evals_dir)), encoding="utf-8")
    return path
