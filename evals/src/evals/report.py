"""Generate `evals/results.md` from run files only (design D8): every number is traceable to a
file under `evals/runs/`. Nothing here is ever edited by hand."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

HEADER = """# Eval results

> Generated by `uv run evals report` from the run files in `evals/runs/`. **Do not edit by hand.**
"""

COLUMNS = [
    "#", "Config", "nDCG@10", "R@5", "R@20", "R@50", "MRR", "Faithfulness", "Answer rel.",
    "Route acc.", "SQL acc.", "Abstain acc.", "p50 e2e ms", "p95 e2e ms", "p95 rerank ms",
    "Cost/query (est.)", "Tokens/query", "Degraded", "Run",
]  # fmt: skip

LIMITATIONS = """## Limitations

- Small n per question type (e.g. 8 unanswerable); n is shown per metric and no claim of
  statistical significance is made.
- The dataset was LLM-generated and agent-verified against the source chunks; human review is
  pending.
- The judge is the same model family as the generator (self-preference bias is possible).
- Cost/query is an estimate from token counts x `pricing.yaml`; the default prices are 0.
"""


def _f(value: float | None, digits: int = 3) -> str:
    return "-" if value is None else f"{value:.{digits}f}"


def _ms(value: float | None) -> str:
    return "-" if value is None else f"{value:,.0f}"


def _mean(d: dict[str, Any] | None) -> float | None:
    return None if not d else d.get("mean")


def _val(d: dict[str, Any] | None) -> float | None:
    return None if not d else d.get("value")


def load_eligible_runs(evals_dir: Path) -> list[tuple[Path, dict[str, Any]]]:
    """Latest results-eligible run file per config (full dataset, non-replay, generation on)."""
    best: dict[str, tuple[str, Path, dict[str, Any]]] = {}
    for path in sorted((evals_dir / "runs").glob("*/*.json")):
        try:
            rec = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if not isinstance(rec, dict) or not rec.get("results_eligible"):
            continue
        name = rec["config"]["name"]
        stamp = rec["finished_at"]
        if name not in best or stamp > best[name][0]:
            best[name] = (stamp, path, rec)
    runs = [(p, r) for _, p, r in best.values()]
    runs.sort(key=lambda pr: (pr[1]["config"].get("grid_row") or 99, pr[1]["config"]["name"]))
    return runs


def _row(evals_dir: Path, path: Path, rec: dict[str, Any]) -> list[str]:
    m = rec["metrics"]
    r = m["retrieval"]
    ans = m.get("answers", {})
    rt = m["routing"]
    lat = m["latency"]
    cst = m["cost"]
    link = path.relative_to(evals_dir).as_posix()
    degraded = rec["degraded"]
    deg = f"{degraded['rate'] * 100:.1f}%" + (" ⚠" if degraded["count"] else "")
    if rec["errors"]["count"]:
        deg += f" ({rec['errors']['count']} errors ⚠)"
    return [
        str(rec["config"].get("grid_row") or "-"),
        f"`{rec['config']['name']}`",
        _f(_mean(r["ndcg_at_10"])),
        _f(_mean(r["recall_at_5"])),
        _f(_mean(r["recall_at_20"])),
        _f(_mean(r["recall_at_50"])),
        _f(_mean(r["mrr"])),
        _f(_mean(ans.get("faithfulness"))),
        _f(_mean(ans.get("answer_relevance"))),
        _f(_val(rt["route_accuracy"])),
        _f(_val(rt["sql_accuracy"])),
        _f(_val(ans.get("abstention_accuracy"))),
        _ms(lat["e2e"]["p50"]),
        _ms(lat["e2e"]["p95"]),
        _ms(lat["stages"].get("rerank", {}).get("p95")),
        f"{cst['cost_per_query']:.4f} (est.)",
        f"{cst['tokens_per_query']:,.0f}",
        deg,
        f"[{rec['run_id']}]({link})",
    ]


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def render_results(evals_dir: Path, runs: list[tuple[Path, dict[str, Any]]]) -> str:
    out = [HEADER]
    if not runs:
        out.append("No full-dataset runs yet. Run `make eval` to produce them.\n")
        return "\n".join(out)

    ds = runs[0][1]["dataset"]
    out.append(
        f"Dataset: `{ds['path']}` ({ds['total_records']} questions, sha256 `{ds['sha256']}`). "
        "Questions were LLM-generated and agent-verified; **human review is pending**.\n"
    )
    out.append("## Ablation grid\n")
    out.append(_table(COLUMNS, [_row(evals_dir, p, r) for p, r in runs]))
    out.append("")

    # coverage
    cov_rows = []
    for _, r in runs:
        m = r["metrics"]
        ans = m.get("answers", {})
        cov_rows.append(
            [
                f"`{r['config']['name']}`",
                str(m["retrieval"]["ndcg_at_10"]["n"]),
                str(m["routing"]["route_accuracy"]["n"]),
                str(m["routing"]["sql_accuracy"]["n"]),
                str(ans.get("faithfulness", {}).get("n", "-")),
                str(ans.get("answer_relevance", {}).get("n", "-")),
                str(ans.get("faithfulness", {}).get("judge_errors", "-")),
                str(ans.get("abstention_accuracy", {}).get("n", "-")),
            ]
        )
    out.append("### Questions covered per metric\n")
    out.append(
        _table(
            [
                "Config",
                "Retrieval (n)",
                "Route (n)",
                "SQL (n)",
                "Faithfulness (n)",
                "Answer rel. (n)",
                "Judge errors",
                "Abstention (n)",
            ],
            cov_rows,
        )
    )
    out.append("")

    # per-stage latency
    stages = sorted({s for _, r in runs for s in r["metrics"]["latency"]["stages"]})
    out.append("## Per-stage latency (ms, p50 / p95)\n")
    header = ["Stage", *[f"`{r['config']['name']}`" for _, r in runs]]
    rows = [
        [
            s,
            *[
                (
                    f"{_ms(st['p50'])} / {_ms(st['p95'])}"
                    if (st := r["metrics"]["latency"]["stages"].get(s))
                    else "-"
                )
                for _, r in runs
            ],
        ]
        for s in stages
    ]
    rows.insert(
        0,
        [
            "server total",
            *[
                f"{_ms(r['metrics']['latency']['server_total']['p50'])} / "
                f"{_ms(r['metrics']['latency']['server_total']['p95'])}"
                for _, r in runs
            ],
        ],
    )
    out.append(_table(header, rows))
    out.append("")

    # confusion matrices for configs with routing enabled
    for _, r in runs:
        if r["config"]["content"]["pipeline"]["routing"]["enabled"]:
            cm = r["metrics"]["routing"]["confusion"]
            out.append(f"## Routing confusion matrix: `{r['config']['name']}`\n")
            out.append(
                _table(
                    ["expected \\ actual", "sql", "vector"],
                    [
                        [f"**{e}**", str(cm[e]["sql"]), str(cm[e]["vector"])]
                        for e in ("sql", "vector")
                    ],
                )
            )
            out.append("")

    # provenance
    prov = []
    for _, r in runs:
        d = r["model_digests"]["digests"]
        prov.append(
            [
                f"`{r['config']['name']}`",
                f"`{r['run_id']}`",
                str(r["seed"]),
                *[f"`{(v or 'unknown')[:12]}`" for v in d.values()],
                f"`{r['git']['sha']}`" + (" (dirty)" if r["git"]["dirty"] else ""),
                "yes" if r["model_digests"]["matches_lock"] else "NO (drift allowed)",
            ]
        )
    digest_names = list(runs[0][1]["model_digests"]["digests"])
    out.append("## Provenance\n")
    out.append(
        _table(
            [
                "Config",
                "Run id",
                "Seed",
                *[f"{n} digest" for n in digest_names],
                "Git sha",
                "Digests match lock",
            ],
            prov,
        )
    )
    out.append("")
    out.append(LIMITATIONS)
    return "\n".join(out)


def write_results(evals_dir: Path) -> Path:
    runs = load_eligible_runs(evals_dir)
    path = evals_dir / "results.md"
    path.write_text(render_results(evals_dir, runs), encoding="utf-8")
    return path
